  function readSavedLanguage() {
    let stored;
    try {
      stored = window.localStorage.getItem(languageStorageKey);
    } catch (error) {
      console.error("No se pudo leer el idioma guardado del sitio.", error);
      return null;
    }

    if (!stored) return null;

    let preference;
    try {
      preference = JSON.parse(stored);
    } catch (error) {
      console.error("La preferencia de idioma guardada no es válida.", error);
      try {
        window.localStorage.removeItem(languageStorageKey);
      } catch (removeError) {
        console.error("No se pudo eliminar la preferencia de idioma no válida.", removeError);
      }
      return null;
    }

    if (
      !preference ||
      typeof preference.language !== "string" ||
      !Number.isFinite(preference.expiresAt)
    ) {
      try {
        window.localStorage.removeItem(languageStorageKey);
      } catch (error) {
        console.error("No se pudo eliminar la preferencia de idioma no válida.", error);
      }
      return null;
    }

    if (preference.expiresAt <= Date.now()) {
      try {
        window.localStorage.removeItem(languageStorageKey);
      } catch (error) {
        console.error("No se pudo eliminar una preferencia de idioma vencida.", error);
      }
      return null;
    }

    const language = normalizeLanguage(preference.language);
    if (!language) {
      try {
        window.localStorage.removeItem(languageStorageKey);
      } catch (error) {
        console.error("No se pudo eliminar la preferencia de idioma no válida.", error);
      }
    }
    return language;
  }

